-- 데이터 정리: 독립 카테고리였던 "센터체험" → "현장직업체험" 의 세부항목으로 병합
-- ================================================================
-- 실제 수요신청서 원본을 보면 "1. 현장직업체험" 아래에 "현장직업체험(체험처)"
-- (외부 체험처 방문) 와 "센터(양재내곡)직업체험"(3D프린팅·로봇공학자·AI작곡가·
-- 드론전문가 세부항목) 이 함께 있다. 그런데 DB 에는 "센터체험"이 세부항목 없는
-- 독립 대분류로, "현장직업체험"이 별도의 대분류로 나뉘어 있어 화면에서 서로
-- 무관한 항목처럼 보였다(사용자 피드백). "센터체험" row 를 지우지 않고
-- "현장직업체험(체험처)" 세부항목으로 재categorize 해 하나로 합친다
-- (이미 연결된 신청 1건은 program_id 가 그대로라 안전).

UPDATE public.programs
   SET category = '현장직업체험',
       sub_program = '현장직업체험(체험처)',
       name = '현장직업체험 · 현장직업체험(체험처)'
 WHERE category = '센터체험'
   AND sub_program IS NULL;
